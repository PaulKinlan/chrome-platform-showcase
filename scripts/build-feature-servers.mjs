#!/usr/bin/env node
// Generates `routes/_feature-servers.generated.ts` from every co-located
// `v<N>/<feature-slug>/_server.ts` on disk.
//
// Why generated: Cloudflare Workers requires a static import graph so Wrangler
// bundles every feature sidecar into the Worker, while hand-editing a central
// `STATIC_FEATURE_SERVERS` map in `routes/release.ts` causes merge conflicts
// whenever two parallel branches add or extract a sidecar.
//
// Usage:
//   node scripts/build-feature-servers.mjs          # write routes/_feature-servers.generated.ts
//   node scripts/build-feature-servers.mjs --check  # fail if the committed file is stale

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "routes", "_feature-servers.generated.ts");

function compareReleaseKey(a, b) {
  const [ar, as] = a.split("/");
  const [br, bs] = b.split("/");
  const diff = Number(ar.slice(1)) - Number(br.slice(1));
  if (diff !== 0) return diff;
  return as.localeCompare(bs);
}

export function discoverFeatureServers(root = ROOT) {
  const found = [];
  for (const rel of readdirSync(root, { withFileTypes: true })) {
    if (!rel.isDirectory() || !/^v\d+$/.test(rel.name)) continue;
    const relDir = join(root, rel.name);
    for (const feat of readdirSync(relDir, { withFileTypes: true })) {
      if (!feat.isDirectory()) continue;
      const serverFile = join(relDir, feat.name, "_server.ts");
      if (existsSync(serverFile)) {
        found.push(`${rel.name}/${feat.name}`);
      }
    }
  }
  return found.sort(compareReleaseKey);
}

export function renderRegistrySource(keys) {
  const lines = [
    "// AUTO-GENERATED by scripts/build-feature-servers.mjs — DO NOT HAND-EDIT.",
    "// Run `npm run gen:feature-servers` after adding or removing any `v<N>/<feature>/_server.ts`.",
    "",
    'import type { FeatureServerHandler } from "../lib/feature-servers/http-helpers.ts";',
  ];

  keys.forEach((key, i) => {
    lines.push(`import { handleFeatureRequest as s${i} } from "../${key}/_server.ts";`);
  });

  lines.push("");
  lines.push(
    "export const GENERATED_FEATURE_SERVERS: Record<string, FeatureServerHandler> = {",
  );
  keys.forEach((key, i) => {
    lines.push(`  "${key}": s${i},`);
  });
  lines.push("};");
  lines.push("");

  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const keys = discoverFeatureServers();
  const expected = renderRegistrySource(keys);

  if (check) {
    const actual = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (actual !== expected) {
      console.error(
        "check-feature-servers: FAIL — routes/_feature-servers.generated.ts is out of date.\n" +
          "Run `npm run gen:feature-servers` to regenerate it.",
      );
      process.exit(1);
    }
    console.log(`check-feature-servers: OK (${keys.length} feature sidecar(s) registered)`);
    return;
  }

  writeFileSync(OUT, expected);
  console.log(
    `build-feature-servers: wrote routes/_feature-servers.generated.ts (${keys.length} sidecar(s))`,
  );
}

if (import.meta.main) main();
